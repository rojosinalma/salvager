local helper = require("spec.helper")

describe("Util", function()
    local Util
    before_each(function() Util = helper.load().Util end)

    it("formats money", function()
        assert.are.equal("0c", Util.FormatMoney(0))
        assert.are.equal("35c", Util.FormatMoney(35))
        assert.are.equal("15s 63c", Util.FormatMoney(1563))
        assert.are.equal("2g 56s 16c", Util.FormatMoney(25616))
        assert.are.equal("1g", Util.FormatMoney(10000))
        assert.are.equal("1g 0s 5c", Util.FormatMoney(10005))
        assert.are.equal("-20s", Util.FormatMoney(-2000))
        assert.are.equal("-", Util.FormatMoney(nil))
    end)

    it("parses money", function()
        assert.are.equal(2000, Util.ParseMoney("20s"))
        assert.are.equal(15000, Util.ParseMoney("1g50s"))
        assert.are.equal(10203, Util.ParseMoney("1g 2s 3c"))
        assert.are.equal(35, Util.ParseMoney("35c"))
        assert.are.equal(2050, Util.ParseMoney("20.5"))
        assert.is_nil(Util.ParseMoney("abc"))
        assert.is_nil(Util.ParseMoney(""))
    end)

    it("fills defaults without overwriting", function()
        local t = Util.Defaults({ a = 1, sub = { x = 5 } }, { a = 2, b = 3, sub = { x = 0, y = 1 } })
        assert.are.equal(1, t.a)
        assert.are.equal(3, t.b)
        assert.are.equal(5, t.sub.x)
        assert.are.equal(1, t.sub.y)
    end)
end)

describe("Util coins", function()
    local Util
    before_each(function() Util = helper.load().Util end)
    it("shows coin icons and turns them back into letters", function()
        local t = Util.FormatMoney(10203, true)
        assert.is_truthy(t:find("UI-GoldIcon", 1, true))
        assert.is_falsy(t:find("g ", 1, true))
        assert.are.equal("1g 2s 3c", Util.PlainMoney(t))
    end)
end)
