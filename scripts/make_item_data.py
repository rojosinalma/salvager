#!/usr/bin/env python3
"""Writes Salvager/NoDisenchant.lua: armor and weapons the game will not disenchant.

Source: the client's item tables from wago.tools (ItemSparse Flags_0 bit 0x8000 = "no disenchant",
Item.ClassID 2/4). WoW Forever's client holds only part of its items (the rest is sent by the
server when first seen), so Classic Era's table fills in the items Forever's table does not have.
Run after each Forever patch:

    python3 scripts/make_item_data.py 1.60.1.71091 1.15.9.70576
"""
import csv, io, sys, urllib.request

FOREVER = sys.argv[1] if len(sys.argv) > 1 else "1.60.1.71091"
CLASSIC = sys.argv[2] if len(sys.argv) > 2 else "1.15.9.70576"
NO_DISENCHANT = 0x8000


def table(name, build):
    url = f"https://wago.tools/db2/{name}/csv?build={build}"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=180) as r:
        return list(csv.DictReader(io.StringIO(r.read().decode("utf-8"))))


def gear(build):
    """{itemID: no_disenchant} for green, blue and purple armor and weapons."""
    classes = {int(r["ID"]): int(r["ClassID"]) for r in table("Item", build)}
    out = {}
    for r in table("ItemSparse", build):
        i = int(r["ID"])
        if classes.get(i) in (2, 4) and int(r["OverallQualityID"]) in (2, 3, 4):
            out[i] = bool(int(r["Flags_0"]) & NO_DISENCHANT)
    return out


forever, classic = gear(FOREVER), gear(CLASSIC)
flags = dict(classic)
flags.update(forever)
ids = sorted(i for i, no in flags.items() if no)
from_classic = sum(1 for i in ids if i not in forever)

lines = []
for i in range(0, len(ids), 14):
    lines.append("    " + ", ".join(str(x) for x in ids[i:i + 14]) + ",")
out = f"""-- Salvager: gear the game will not disenchant (GENERATED by scripts/make_item_data.py).
-- {len(ids)} green, blue and purple armor and weapons with the client's "no disenchant" item flag:
-- WoW Forever {FOREVER}, plus {from_classic} from Classic Era {CLASSIC} for items Forever's client table lacks.
local _, ns = ...
ns = ns or {{}}

local set = {{}}
for _, id in ipairs({{
{chr(10).join(lines)}
}}) do set[id] = true end

--- True when the game refuses to disenchant this item ID.
function ns.NoDisenchant(itemID)
    return itemID ~= nil and set[itemID] == true
end
"""
open("Salvager/NoDisenchant.lua", "w").write(out)
print(f"{len(ids)} items ({from_classic} from Classic Era); gear known: forever {len(forever)}, classic {len(classic)}")
