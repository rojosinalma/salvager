#!/usr/bin/env python3
"""Writes Salvager/NoDisenchant.lua: armor and weapons the game will not disenchant.

Source: the client's own item tables (ItemSparse Flags_0 bit 0x8000 = "no disenchant",
Item.ClassID 2/4), from wago.tools. Run after each Forever patch:

    python3 scripts/make_no_disenchant.py 1.60.1.71091
"""
import csv, io, sys, urllib.request

BUILD = sys.argv[1] if len(sys.argv) > 1 else "1.60.1.71091"
NO_DISENCHANT = 0x8000


def table(name):
    url = f"https://wago.tools/db2/{name}/csv?build={BUILD}"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return csv.DictReader(io.StringIO(r.read().decode("utf-8")))


classes = {int(r["ID"]): int(r["ClassID"]) for r in table("Item")}
ids = sorted(
    int(r["ID"]) for r in table("ItemSparse")
    if int(r["Flags_0"]) & NO_DISENCHANT and classes.get(int(r["ID"])) in (2, 4)
    and int(r["OverallQualityID"]) in (2, 3, 4)
)

lines = []
for i in range(0, len(ids), 14):
    lines.append("    " + ", ".join(str(x) for x in ids[i:i + 14]) + ",")
out = f"""-- Salvager: gear the game will not disenchant (GENERATED by scripts/make_no_disenchant.py, build {BUILD}).
-- {len(ids)} green, blue and purple armor and weapons with the client's "no disenchant" item flag.
local _, ns = ...
ns = ns or {{}}

local set = {{}}
for _, id in ipairs({{
{chr(10).join(lines)}
}}) do set[id] = true end

--- True when the game refuses to disenchant this item ID.
function ns.NoDisenchant(itemID)
    return itemID ~= nil and set[itemID] == true
end
"""
open("Salvager/NoDisenchant.lua", "w").write(out)
print(f"{len(ids)} items")
